      header: { fgColor: "%s", bgColor: "default", sorterColor: "%s" }
    yaml: { keyColor: "%s", colonColor: "%s", valueColor: "%s" }
    logs: { fgColor: "%s", bgColor: "default" }
]]):format(p.name,
    p.text, p.accent, p.text, p.base, p.accent, p.accent, p.text,
    p.text, p.text, p.surface, p.base, p.accent, p.subtext, p.text,
    p.surface, p.accent, p.text, p.accent, p.yellow,
    p.subtext, p.base, p.accent,
    p.green, p.yellow, p.green, p.red, p.accent, p.red, p.blue,
    p.text, p.accent, p.accent, p.yellow,
    p.text, p.accent, p.accent, p.accent, p.subtext, p.text, p.subtext, p.text)
  writeFile("~/.config/k9s/skins/omachy.yaml", skin)
  -- Only patch an existing config.yaml — let k9s generate its own on first run
  -- (a hand-written stub trips its schema check on newer versions). Run k9s
  -- once, then switch theme again to wire `ui.skin`.
  local conf = readFile("~/.config/k9s/config.yaml")
  if conf and conf:match("skin:") then
    writeFile("~/.config/k9s/config.yaml", conf:gsub("skin:%s*[%w_-]*", "skin: omachy"))
  elseif conf and conf:match("\n  ui:") then
    writeFile("~/.config/k9s/config.yaml", conf:gsub("(\n  ui:\n)", "%1    skin: omachy\n", 1))
  end
end

-- nvim: LazyVim reads this name via lua/plugins/omachy-colorscheme.lua.
local function applyNvim(p)
  writeFile("~/.config/nvim/omachy-theme.txt", p.nvim .. "\n")
end

local function applyWallpaper(p)
  if not (M.setWallpaper and p.wallpaper) then return end
  local path = HOME .. "/Pictures/Wallpapers/" .. p.wallpaper
  if hs.fs.attributes(path) then
    hs.osascript.applescript(
      ('tell application "System Events" to tell every desktop to set picture to %q'):format(path))
  end
end

local function applyAppearance(p)
  if not M.setAppearance then return end
  hs.osascript.applescript(
    ('tell application "System Events" to tell appearance preferences to set dark mode to %s')
      :format(tostring(p.dark)))
end

-- ── change subscribers (Hammerspoon UI) ────────────────────────────────────
M._subs = {}
function M.onChange(fn) M._subs[#M._subs + 1] = fn end

local function applyHammerspoon(p)
  hs.alert.defaultStyle.fillColor   = { hex = p.mantle, alpha = 0.97 }
  hs.alert.defaultStyle.strokeColor = { hex = p.accent, alpha = 1 }
  hs.alert.defaultStyle.textColor   = { hex = p.text }
  hs.alert.defaultStyle.textFont    = "Hack Nerd Font Mono"
  hs.alert.defaultStyle.radius      = 0
  for _, fn in ipairs(M._subs) do pcall(fn, p) end
end

-- ── public API ─────────────────────────────────────────────────────────────
function M.current()
  return byName(settings.get(KEY) or "") or palettes[1]
end
M.colors = M.current            -- alias other modules use

function M.apply(name, opts)
  opts = opts or {}
  local p = byName(name) or M.current()
  local steps = {
    applyHammerspoon, applyBorders, applySketchybar, applyGhostty,
    applyBat, applyStarship, applyBtop, applyK9s, applyNvim,
  }
  if not opts.soft then                     -- skip on a plain reload
    steps[#steps + 1] = applyWallpaper
    steps[#steps + 1] = applyAppearance
  end
  for _, step in ipairs(steps) do
    local ok, err = pcall(step, p)
    if not ok then log.ef("apply %s: %s", p.name, err) end
  end
  return p
end

function M.set(name)
  local p = byName(name)
  if not p then hs.alert.show("theme: no '" .. tostring(name) .. "'"); return end
  settings.set(KEY, p.name)
  M.apply(p.name)
  hs.alert.show("  " .. p.label)
end

function M.cycle(dir)
  dir = dir or 1
  local cur = M.current().name
  local i = 1
  for idx, p in ipairs(palettes) do if p.name == cur then i = idx break end end
  local nxt = palettes[((i - 1 + dir) % #palettes) + 1]
  M.set(nxt.name)
end

-- rows for the Opt+Space menu: { name, action, marked }
function M.list()
  local cur = M.current().name
  local out = {}
  for _, p in ipairs(palettes) do
    out[#out + 1] = {
      name = p.label .. (p.name == cur and "   ✓" or ""),
      action = function() M.set(p.name) end,
    }
  end
  return out
end

return M
