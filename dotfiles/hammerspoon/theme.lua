    buttonFocusBgColor: "%s"
    labelFgColor: "%s"
    fieldFgColor: "%s"
  frame:
    border: { fgColor: "%s", focusColor: "%s" }
    menu: { fgColor: "%s", keyColor: "%s", numKeyColor: "%s" }
    crumbs: { fgColor: "%s", bgColor: "%s", activeColor: "%s" }
    status:
      newColor: "%s"
