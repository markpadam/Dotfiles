-- theme.lua — one command re-skins the whole desktop.
--
-- Omarchy's signature trick: pick a theme and Ghostty, JankyBorders,
-- SketchyBar, the shell prompt, bat, btop, k9s, Neovim, the wallpaper and every
-- Hammerspoon panel (menu / OSD / which-key / clipboard) all change together.
--
-- The catalogue is `palettes.lua`. This file converts each palette into the
-- shape every target wants and applies it, then remembers the choice in
-- `hs.settings` so `init.lua` can re-assert it on login.
--
--   require("theme").set("nord")        -- apply + persist + toast
--   require("theme").cycle(1)           -- next theme  (Ctrl+Alt+Space)
--   require("theme").current()          -- active palette table
--   require("theme").onChange(fn)       -- fn(palette) on every change
--
-- Targets that reload live: Hammerspoon UI, JankyBorders, SketchyBar, Ghostty,
-- wallpaper, macOS light/dark. Targets that need a fresh process: bat, btop,
-- k9s, Neovim, the shell prompt (open a new window / `exec zsh`).

local settings = require("hs.settings")
local palettes = require("palettes")

local M = {}
local HOME = os.getenv("HOME")
local KEY  = "omachy.theme"
local log  = hs.logger.new("theme", "info")

M.themes = palettes
M.setAppearance = true       -- also flip macOS light/dark to match the theme
M.setWallpaper  = true       -- also set the palette's wallpaper if it exists

-- ── helpers ────────────────────────────────────────────────────────────────
local function byName(name)
  for _, p in ipairs(palettes) do if p.name == name then return p end end
end

-- "#rrggbb" -> "0xAArrggbb"  (AA defaults to ff / opaque)
local function bar(hex, aa)
  return "0x" .. (aa or "ff") .. hex:gsub("#", ""):lower()
end

local function writeFile(path, body)
  path = path:gsub("^~", HOME)
  hs.execute(("mkdir -p %q"):format(path:match("^(.*)/[^/]*$")))
  local f, err = io.open(path, "w")
  if not f then log.ef("write %s: %s", path, err); return false end
  f:write(body); f:close()
  return true
end

local function readFile(path)
  local f = io.open((path:gsub("^~", HOME)), "r")
  if not f then return nil end
  local s = f:read("*a"); f:close(); return s
end

-- run a shell command async, log non-zero exits. GUI-launched Hammerspoon has
-- a bare PATH, so prepend Homebrew's bin for `sketchybar` / `borders` / etc.
local function sh(cmd)
  hs.task.new("/bin/sh", function(rc, _, se)
    if rc ~= 0 then log.wf("`%s` exited %d %s", cmd, rc, (se or ""):gsub("%s+$", "")) end
  end, { "-c", "export PATH=/opt/homebrew/bin:/usr/bin:/bin:$PATH; " .. cmd }):start()
end

-- ── per-target appliers ────────────────────────────────────────────────────

-- JankyBorders: update the running daemon now, and drop a theme.sh that
-- bordersrc sources so a daemon restart keeps the colour.
local function applyBorders(p)
  local active   = ("glow(%s)"):format(bar(p.accent))
  local inactive = bar(p.surface)
  writeFile("~/.config/borders/theme.sh", ("# generated by hammerspoon/theme.lua — %s\n"):format(p.name)
    .. ("active_color=\"%s\"\n"):format(active)
    .. ("inactive_color=\"%s\"\n"):format(inactive))
  sh(("borders active_color=%q inactive_color=%q"):format(active, inactive))
end

-- SketchyBar: theme.sh of exported 0x colours, sourced by sketchybarrc.
local function applySketchybar(p)
  local body = ([[# generated by hammerspoon/theme.lua — %s
export BAR_BG=%s
export BAR_EXTERNAL=%s
export BAR_ISLAND=%s
export BAR_BORDER=%s
export BAR_ACCENT=%s
export BAR_ACCENT_DIM=%s
export BAR_ACCENT_B=%s
export BAR_TEXT=%s
export BAR_SUBTEXT=%s
export BAR_SURFACE=%s
export BAR_RED=%s
export BAR_GREEN=%s
export BAR_YELLOW=%s
export BAR_BLUE=%s
]]):format(p.name,
    bar(p.base, "f0"), bar(p.base, "cc"), bar(p.mantle, "f0"), bar(p.accent),
    bar(p.accent), bar(p.accent, "1a"), bar(p.accent, "40"),
    bar(p.text), bar(p.subtext), bar(p.surface),
    bar(p.red), bar(p.green), bar(p.yellow), bar(p.blue))
  writeFile("~/.config/sketchybar/theme.sh", body)
  sh("sketchybar --reload")
end

-- Ghostty: theme.conf (last include in config wins) + reload the running app.
local function applyGhostty(p)
  writeFile("~/.config/ghostty/theme.conf",
    ("# generated by hammerspoon/theme.lua — do not edit\ntheme = %s\n"):format(p.ghostty))
  local app = hs.application.get("com.mitchellh.ghostty")
  if not app then return end
  if not app:selectMenuItem("Reload Configuration")
     and not app:selectMenuItem({ "Ghostty", "Reload Configuration" }) then
    sh("/usr/bin/pkill -USR2 -x ghostty")   -- best effort; harmless if unsupported
  end
end

-- bat: validate the requested theme against the installed set, fall back sanely.
local function applyBat(p)
  hs.task.new("/opt/homebrew/bin/bat", function(_, out)
    local want, ok = p.bat, false
    for line in (out or ""):gmatch("[^\n]+") do if line == want then ok = true break end end
    if not ok then want = p.dark and "ansi" or "GitHub" end
    writeFile("~/.config/bat/config", ('--theme="%s"\n--paging=never\n'):format(want))
  end, { "--list-themes" }):start()
end

-- starship: two shapes of config in the wild —
--   * palette-based (repo's config/starship.toml): flip the `palette = '...'` line
--   * our minimal "Omachy Starship prompt" config: regenerate from a template
--     so it re-themes deterministically (and reversibly)
local STARSHIP_TEMPLATE = [[# Omachy Starship prompt — %s (managed by hammerspoon/theme.lua)

format = """
$directory\
$git_branch\
$git_status\
$character"""

[directory]
style = "bold %s"
truncation_length = 3

[git_branch]
symbol = " "
style = "bold %s"

[git_status]
style = "bold %s"

[character]
success_symbol = "[❯](bold %s)"
error_symbol = "[❯](bold %s)"
]]

local function applyStarship(p)
  local path = HOME .. "/.config/starship.toml"
  local body = readFile(path)
  if not body then return end
  local new
  if body:find("palette = '") then
    new = body:gsub("palette = '[%w_]+'", ("palette = '%s'"):format(p.starship), 1)
  elseif body:find("Omachy Starship prompt", 1, true) then
    new = STARSHIP_TEMPLATE:format(p.label, p.blue, p.green, p.yellow, p.accent, p.red)
  else
    return   -- unknown custom config: leave it alone
  end
  if new ~= body then writeFile(path, new) end
end

