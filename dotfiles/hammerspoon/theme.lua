    p.surface, p.surface, p.green, p.yellow, p.red, p.green, p.yellow, p.red,
    p.blue, p.accent, p.red, p.green, p.blue)
  writeFile("~/.config/btop/themes/omachy.theme", t)
  local conf = readFile("~/.config/btop/btop.conf")
  if conf and conf:match('color_theme%s*=') then
    writeFile("~/.config/btop/btop.conf",
      conf:gsub('color_theme%s*=%s*"[^"]*"', 'color_theme = "omachy"'))
  elseif not conf then
    writeFile("~/.config/btop/btop.conf",
      'color_theme = "omachy"\ntheme_background = False\ntruecolor = True\n')
  end
end

